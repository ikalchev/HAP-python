def test_receiver_rejects_unknown_kid() -> None:
    """Verify frames for a KID without a receive key are rejected."""
    sender = SFrameSender(bytes(32), 5, 1, SFrameSuite.HOMEKIT_AUDIO)
    receiver = SFrameReceiver()
    receiver.update_keys([(bytes(32), 6)], [])
    with pytest.raises(SFrameError, match="Unknown"):
        receiver.unprotect(sender.protect(b"opus"), 1)


def test_receiver_remove_key() -> None:
    """Verify a removed KID no longer decrypts."""
    sender = SFrameSender(bytes(32), 5, 1, SFrameSuite.HOMEKIT_AUDIO)
    receiver = SFrameReceiver()
    receiver.update_keys([(bytes(32), 5)], [])
    assert receiver.unprotect(sender.protect(b"a"), 1) == b"a"
    receiver.update_keys([], [5])
    assert not receiver.has_keys
    with pytest.raises(SFrameError, match="Unknown"):
        receiver.unprotect(sender.protect(b"b"), 1)


def test_receiver_rejects_tampered_frame() -> None:
    """Verify a modified tag fails authentication."""
    frame = bytearray(
        SFrameSender(bytes(32), 1, 1, SFrameSuite.HOMEKIT_VIDEO).protect(b"x")
    )
    frame[-1] ^= 1
    receiver = SFrameReceiver(SFrameSuite.HOMEKIT_VIDEO)
    receiver.update_keys([(bytes(32), 1)], [])
    with pytest.raises(SFrameError, match="authentication"):
        receiver.unprotect(bytes(frame), 1)


def test_receiver_rejects_wrong_ssrc() -> None:
    """Verify the per-SSRC key binds a frame to its RTP stream."""
    frame = SFrameSender(bytes(32), 1, 1, SFrameSuite.HOMEKIT_AUDIO).protect(b"x")
    receiver = SFrameReceiver()
    receiver.update_keys([(bytes(32), 1)], [])
