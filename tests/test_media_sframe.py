"""Tests for pyhap.media.sframe.

``data/sframe_rfc9605_vectors.json`` holds the RFC 9605 Appendix C test
vectors for the AES-CTR/HMAC suites (ten of the header cases, AEAD and SFrame
encryption).
``data/sframe_scrypted_vectors.json`` was generated by running Scrypted's
``plugins/webrtc/src/sframe*.ts`` with node at the commit it names, see
``scripts/gen_sframe_scrypted_vectors.ts``.
"""

from __future__ import annotations

from typing import Any

import pytest

from pyhap.media import sframe
from pyhap.media.sframe import (
    SFrameDepacketizer,
    SFrameError,
    SFrameKeys,
    SFrameReceiver,
    SFrameSender,
    SFrameSuite,
)

from .webrtc_helpers import blob, load_vectors, plaintext, seeded_bytes

RFC = load_vectors("sframe_rfc9605_vectors.json")
SCRYPTED = load_vectors("sframe_scrypted_vectors.json")


def number(value: str) -> int:
    """Parse a vector number, either 0x-prefixed hex or decimal."""
    return int(value, 0)


def scrypted_frames() -> list[tuple[dict[str, Any], dict[str, Any]]]:
    """Flatten the Scrypted stream vectors to (stream, frame) pairs."""
    return [
        (stream, frame) for stream in SCRYPTED["streams"] for frame in stream["frames"]
    ]


def field(items: list[dict[str, Any]], name: str) -> list[Any]:
    """Collect one field of every item."""
    return [item[name] for item in items]


def protect_stream(stream: dict[str, Any]) -> list[Any]:
    """Protect every frame of a Scrypted stream vector in order."""
    sender = SFrameSender(
        bytes.fromhex(stream["key"]),
        int(stream["kid"]),
        stream["ssrc"],
        SFrameSuite(stream["suite"]),
    )
    sender.counter = int(stream["frames"][0]["counter"])
    return [blob(sender.protect(plaintext(frame["pt"]))) for frame in stream["frames"]]


def packetize_frames(case: dict[str, Any]) -> list[list[dict[str, Any]]]:
    """Packetize the Scrypted packetizer vector frames like Scrypted does."""
    sender = SFrameSender(
        bytes.fromhex(case["key"]), int(case["kid"]), case["ssrc"], case["suite"]
    )
    sequence = 65530
    out = []
    for frame in case["frames"]:
        payloads = sframe.packetize(
            sender.protect(plaintext(frame["pt"])), case["max_payload"]
        )
        packets = []
        for index, payload in enumerate(payloads):
            packets.append(
                {
                    "sequence": sequence,
                    "marker": index == len(payloads) - 1,
                    "payload": blob(payload),
                }
            )
            sequence = (sequence + 1) & 0xFFFF
        out.append(packets)
    return out


def run_receiver(case: dict[str, Any]) -> list[dict[str, Any]]:
    """Feed the replay vector through a receiver, recording each outcome.

    The payloads are rebuilt with an SFrameSender; their digests must match
    the vector, and every accepted frame must decrypt to its plaintext.
    """
    key, kid, ssrc = bytes.fromhex(case["key"]), int(case["kid"]), case["ssrc"]
    sender = SFrameSender(key, kid, ssrc, SFrameSuite.HOMEKIT_AUDIO)
    receiver = SFrameReceiver(SFrameSuite.HOMEKIT_AUDIO)
    receiver.update_keys([(key, kid)], [])
    steps = []
    for step in case["steps"]:
        counter = step["counter"]
        opus = seeded_bytes(f"opus-{counter}", 60)
        sender.counter = counter
        payload = bytes([0xC0]) + sender.protect(opus)
        result = {"counter": counter, "payload": blob(payload), "accepted": True}
        try:
            result["accepted"] = receiver.unprotect(payload[1:], ssrc) == opus
        except SFrameError:
            result["accepted"] = False
        steps.append(result)
    return steps


@pytest.mark.parametrize("case", RFC["header"])
def test_rfc_header_encode(case: dict[str, str]) -> None:
    """Verify header encoding against RFC 9605 C.1."""
    assert (
        sframe.encode_header(number(case["kid"]), number(case["ctr"])).hex()
        == (case["header"])
    )


@pytest.mark.parametrize("case", RFC["header"])
def test_rfc_header_decode(case: dict[str, str]) -> None:
    """Verify header decoding against RFC 9605 C.1."""
    header = bytes.fromhex(case["header"])
    assert sframe.decode_header(header + b"rest") == (
        number(case["kid"]),
        number(case["ctr"]),
        len(header),
    )


@pytest.mark.parametrize("case", RFC["aead"])
def test_rfc_aead(case: dict[str, str]) -> None:
    """Verify the AES-CTR/HMAC AEAD against RFC 9605 C.2."""
    suite = SFrameSuite(number(case["cipher_suite"]))
    key, nonce, aad = (
        bytes.fromhex(case["key"]),
        bytes.fromhex(case["nonce"]),
        bytes.fromhex(case["aad"]),
    )
    ct = sframe.aead_encrypt(suite, key, nonce, aad, bytes.fromhex(case["pt"]))
    assert ct.hex() == case["ct"]
    assert sframe.aead_decrypt(suite, key, nonce, aad, ct).hex() == case["pt"]


@pytest.mark.parametrize("case", RFC["sframe"])
def test_rfc_sframe(case: dict[str, str]) -> None:
    """Verify key derivation and frame protection against RFC 9605 C.3."""
    suite = SFrameSuite(number(case["cipher_suite"]))
    keys = sframe.derive_key_salt(
        bytes.fromhex(case["base_key"]), number(case["kid"]), suite
    )
    assert keys == SFrameKeys(
        bytes.fromhex(case["sframe_key"]), bytes.fromhex(case["sframe_salt"])
    )
    metadata = bytes.fromhex(case["metadata"])
    frame = sframe.protect(
        keys,
        suite,
        number(case["kid"]),
        number(case["ctr"]),
        bytes.fromhex(case["pt"]),
        metadata,
    )
    assert frame.hex() == case["ct"]
    assert sframe.unprotect(keys, suite, frame, metadata).hex() == case["pt"]


