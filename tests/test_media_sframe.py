@pytest.mark.parametrize("size", [1, 10, 11, 25, 100])
def test_depacketize_round_trip(size: int) -> None:
    """Verify descriptor packetization reassembles across a sequence wrap."""
    frame = seeded_bytes(f"frame-{size}", size)
    packets = numbered(sframe.packetize(frame, 11), 65534)
    assert reassemble(packets) == [frame]


def test_depacketize_drops_frame_with_gap() -> None:
    """Verify a missing middle packet drops the frame, not the next one."""
    first = numbered(sframe.packetize(b"a" * 30, 11), 0)
    second = numbered(sframe.packetize(b"b" * 5, 11), 3)
    assert reassemble([first[0], first[2], *second]) == [b"b" * 5]


def test_depacketize_drops_continuation_without_start() -> None:
    """Verify packets of a frame whose start was lost are ignored."""
    parts = numbered(sframe.packetize(b"c" * 30, 11), 10)
    assert reassemble(parts[1:]) == []


def test_depacketize_ignores_empty_payload() -> None:
    """Verify an empty payload aborts the current frame."""
    parts = sframe.packetize(b"c" * 30, 11)
    assert reassemble(numbered([parts[0], b"", parts[1], parts[2]], 0)) == []


def numbered(payloads: list[bytes], sequence: int) -> list[tuple[int, bytes]]:
    """Pair payloads with consecutive RTP sequence numbers."""
    return [((sequence + i) & 0xFFFF, p) for i, p in enumerate(payloads)]


def reassemble(
    packets: list[tuple[int, bytes]], depacketizer: SFrameDepacketizer | None = None
) -> list[bytes]:
    """Push packets into a depacketizer and collect the completed frames."""
    depacketizer = depacketizer or SFrameDepacketizer()
    frames = []
    for sequence, payload in packets:
        frame = depacketizer.push(sequence, payload)
        if frame is not None:
            frames.append(frame)
    return frames


def test_update_keys_is_atomic() -> None:
    """Verify an invalid key in an update leaves the old keys in place."""
    sender = SFrameSender(bytes(32), 5, 1, SFrameSuite.HOMEKIT_AUDIO)
    receiver = SFrameReceiver()
    receiver.update_keys([(bytes(32), 5)], [])
    with pytest.raises(SFrameError, match="32 bytes"):
        receiver.update_keys([(bytes(32), 6), (bytes(3), 7)], [5])
    assert receiver.unprotect(sender.protect(b"kept"), 1) == b"kept"


def test_update_keys_limits_key_count() -> None:
    """Verify the number of receive keys is bounded."""
    receiver = SFrameReceiver()
    with pytest.raises(SFrameError, match="Too many"):
        receiver.update_keys(zero_keys(sframe.MAX_RECEIVE_KEYS + 1), [])
    assert not receiver.has_keys


def test_receiver_bounds_stream_state() -> None:
    """Verify replay state is kept for a bounded number of SSRCs."""
    receiver = SFrameReceiver()
    receiver.update_keys([(bytes(32), 1)], [])
    frames = protected_per_ssrc(sframe.MAX_RECEIVE_STREAMS + 4)
    unprotect_all(receiver, frames)
    assert len(receiver._streams) == sframe.MAX_RECEIVE_STREAMS


def test_unknown_hash_does_not_fall_back() -> None:
    """Verify an unknown hash name fails instead of using another hash."""
    with pytest.raises(KeyError):
        sframe._hash("sha1")


def test_depacketize_drops_oversized_frame() -> None:
    """Verify a frame over the size bound is not reassembled."""
    parts = numbered(sframe.packetize(bytes(100), 11), 0)
    depacketizer = SFrameDepacketizer(max_frame=50)
    assert reassemble(parts, depacketizer) == []


def zero_keys(count: int) -> list[tuple[bytes, int]]:
    """Return ``count`` all-zero keys with KIDs from 0."""
    return [(bytes(32), kid) for kid in range(count)]


def protected_per_ssrc(count: int) -> list[tuple[int, bytes]]:
    """Protect one frame for each of ``count`` SSRCs."""
    suite = SFrameSuite.HOMEKIT_AUDIO
    return [
        (ssrc, SFrameSender(bytes(32), 1, ssrc, suite).protect(b"x"))
        for ssrc in range(count)
    ]


def unprotect_all(receiver: SFrameReceiver, frames: list[tuple[int, bytes]]) -> None:
    """Unprotect ``(ssrc, frame)`` pairs in order."""
    for ssrc, frame in frames:
        receiver.unprotect(frame, ssrc)
