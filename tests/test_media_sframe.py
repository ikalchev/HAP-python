@pytest.mark.parametrize("pair", scrypted_frames())
def test_scrypted_frame_round_trip(
    pair: tuple[dict[str, Any], dict[str, Any]],
) -> None:
    """Verify a receiver decrypts what the sender protected."""
    stream, frame = pair
    key, kid = bytes.fromhex(stream["key"]), int(stream["kid"])
    sender = SFrameSender(key, kid, stream["ssrc"], stream["suite"])
    sender.counter = int(frame["counter"])
    data = plaintext(frame["pt"])
    receiver = SFrameReceiver(stream["suite"])
    receiver.update_keys([(key, kid)], [])
    assert receiver.unprotect(sender.protect(data), stream["ssrc"]) == data


