def test_counter_exhaustion() -> None:
    """Verify the sender refuses to reuse a nonce after 2**64 frames."""
    sender = SFrameSender(bytes(32), 1, 1, SFrameSuite.HOMEKIT_VIDEO)
    sender.counter = sframe.MAX_UINT64
    sender.protect(b"last")
    with pytest.raises(SFrameError, match="exhausted"):
        sender.protect(b"again")


